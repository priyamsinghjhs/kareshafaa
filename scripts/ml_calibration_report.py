"""ML outreach-priority model: calibration + fairness report on a seeded database (read-only on the source DB).

Copies the SQLite DB to a scratch file, trains logreg and gbm candidates with recalibration 'none' (the default)
and 'auto' (Platt, chosen on a temporal tuning slice), and reports held-out (most recent 25 %) discrimination,
calibration (ECE, Brier, calibration-in-the-large, slope, reliability bins with Wilson 95 % CIs) and the fairness
gates. Nothing is promoted; the source database is not modified.

usage: python scripts/ml_calibration_report.py --db data/wasl_large.db --name large [--out docs/ml_calibration]
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def render(data: dict) -> str:
    L = ["# ML outreach-priority model: calibration, fairness and rationale", "",
         "Generated by `scripts/ml_calibration_report.py` (offline; nothing is promoted). Hold-out = most recent 25 % of "
         "labelled cases (temporal split). Label = the case missed its next step / pathway target (delay). "
         "Slope and intercept are from a logistic recalibration of the hold-out outcome on logit(p): slope 1 means "
         "neither over- nor under-confident; CITL = mean predicted - observed rate.", "",
         "**Use:** orders cases *within the same clinical urgency tier* for outreach. It never sets or changes a "
         "tier, a clinical decision, a state or a closure; the rules engine does that.", ""]
    for name, d in data.items():
        L += [f"## {name} (`{d['db']}`, as of {d['as_of']} UTC)", "",
              "| Algorithm | Recalibration setting -> chosen | n train / hold-out | AUC | ECE raw -> final | Slope raw -> final "
              "| CITL | Brier | Reliability bins within 95 % CI | Gates failed |", "|---|---|---|---|---|---|---|---|---|---|"]
        for r in d["results"]:
            L.append(f"| {r['algorithm']} | {r['recalibration']} -> {r['chosen']} | {r['n_train']:,} / {r['n_holdout']:,} | "
                     f"{r['auc']} | {r['raw']['ece']} -> {r['final']['ece']} | {r['raw']['slope']} -> {r['final']['slope']} | "
                     f"{r['final']['citl']} | {r['final']['brier']} | {r['final']['bins_within_ci']}/{r['final']['bins']} | "
                     f"{', '.join(r['gates_failed']) or 'none'} |")
        r0 = next(r for r in d["results"] if r["algorithm"] == "logreg" and r["recalibration"] == "none")
        L += ["", "Reliability (logreg, default setting): mean predicted vs observed with Wilson 95 % CI", "",
              "| Bin | n | Mean predicted | Observed | 95 % CI | Within |", "|---|---|---|---|---|---|"]
        for i, b in enumerate(r0["reliability"], 1):
            L.append(f"| {i} | {b['n']} | {b['mean_pred']} | {b['observed']} | {b['ci'][0]}-{b['ci'][1]} | {'yes' if b['within_ci'] else 'no'} |")
        L += ["", "Fairness (logreg, default setting): group flagged only if its bootstrap 95 % CI lies wholly beyond the "
              "tolerance; `gap` = largest point-estimate gap between groups.", "",
              "| Attribute | AUC gate | AUC gap | Recall gate | Recall gap | Calibration gate |", "|---|---|---|---|---|---|"]
        for attr, f in r0["fairness"].items():
            L.append(f"| {attr} | {'pass' if f['auc']['passed'] else 'FAIL'} ({f['auc']['flagged']}) | {f['auc']['gap']} | "
                     f"{'pass' if f['recall']['passed'] else 'FAIL'} ({f['recall']['flagged']}) | {f['recall']['gap']} | "
                     f"{'pass' if f['calibration']['passed'] else 'FAIL'} ({f['calibration']['flagged']}) |")
        L.append("")
    L += ["## Decisions and limits", "",
          "* **Default recalibration is 'none'.** Logistic regression fitted by log-loss is calibrated in-sample by "
          "construction; on the 2,000-patient demo cohort, Platt recalibration (fitted on out-of-fold predictions and "
          "chosen on a temporal tuning slice) *over-corrected* on the newer hold-out (slope 1.11 -> 1.40) and would "
          "fail the slope gate. On the 20k realistic cohort it was roughly neutral. 'auto' remains available "
          "(`WASL_ML_RECALIBRATION=auto`) once pilot volumes allow it.",
          "* **New promotion gates:** hold-out calibration slope within 0.7-1.3 and |CITL| <= 0.05, in addition to "
          "AUC floor, ECE <= 0.10, beats-current on the same hold-out and the fairness gates. A clinical lead must "
          "still approve every promotion (human sign-off); the person who trained a model cannot approve it.",
          "* **Small samples are blocked:** on the 400-patient test seed the candidates are over-confident "
          "(slope about 0.5) and fail the slope gate, so no model reaches production without more data.",
          "* **Residual CITL of +0.04-0.05:** the model slightly over-predicts delay on the most recent cases, "
          "because the newest cases have had less time to be labelled late (right-censoring). It is within the gate "
          "but should be monitored by the drift report.",
          "* **Rationale per priority:** for each scored case, the three factors that change the predicted delay "
          "risk most versus a typical case (one-at-a-time substitution, threshold 2 points) are stored with the score "
          "and shown in the queue (tooltip) and the case page (\"Why this outreach priority\"). Sensitive attributes "
          "(nationality, gender) are not model inputs, so they never appear in a rationale. This is a local "
          "explanation of the model, not a causal claim.",
          "* **Wide subgroup gaps are not yet evidence of fairness.** Point-estimate recall gaps of 0.27-0.47 between "
          "small subgroups pass only because their confidence intervals are wide. The gate flags a group only when the "
          "whole CI is beyond tolerance, which avoids false alarms but has low power at these sizes; subgroup "
          "monitoring must continue on pilot data, and outreach for under-served groups is not ML-driven (tier and "
          "SLA come first).",
          "* **Language is no longer an identity input (round 18).** After the round-16 re-seed the demo logistic "
          "candidate failed `fairness_recall:language`: English speakers were flagged for priority outreach at 6 % "
          "against an observed delay rate of 18 % (recall 0.12 vs 0.47 overall, bootstrap CI upper bound 0.26 below "
          "the 0.32 limit). The same pattern was in the pre-round-16 data (recall 0.25, CI 0.07-0.43) but not yet "
          "credible. The one-hot `language` input was replaced by `language_unsupported` (no patient material in the "
          "preferred language, i.e. interpreter needed), the operational barrier it stood for. Gates, tolerances and "
          "minimum group sizes are unchanged. Three feature sets were compared on the same hold-outs (one-hot, none, "
          "barrier flag); the choice follows the mechanism but was made after seeing these hold-outs, so it must be "
          "re-checked on fresh data.",
          "* Synthetic data: these numbers say the pipeline and gates work; they are not evidence of real-world "
          "performance. Re-validate on pilot data before relying on the ordering.", ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", default=str(ROOT / "docs" / "ml_calibration"))
    a = ap.parse_args()
    tmp = Path(tempfile.mkdtemp(prefix="mlcal_"))
    import sqlite3  # noqa: PLC0415

    src, dst = sqlite3.connect(f"file:{a.db}?mode=ro", uri=True), sqlite3.connect(tmp / "w.db")
    src.backup(dst)  # consistent copy even with a WAL file; the source is opened read-only
    src.close()
    dst.close()
    os.environ["WASL_DATABASE_URL"] = f"sqlite:///{tmp / 'w.db'}"
    os.environ["WASL_MODEL_DIR"] = str(tmp / "models")
    from sqlalchemy import func, select  # noqa: PLC0415

    from wasl.config import get_settings  # noqa: PLC0415
    from wasl.db import session_factory  # noqa: PLC0415
    from wasl.ml import registry  # noqa: PLC0415
    from wasl.models import AuditEvent, ModelVersion  # noqa: PLC0415
    from wasl.security import Actor  # noqa: PLC0415

    cfg = get_settings()
    db = session_factory()()
    now = db.scalar(select(func.max(AuditEvent.ts)))
    actor = Actor(user_id=None, role="admin", display="calibration report (offline)")
    results = []
    for method in ("none", "auto"):
        cfg.ml_recalibration = method
        for alg in ("logreg", "gbm"):
            for mv in db.scalars(select(ModelVersion).where(ModelVersion.status == "production")):
                mv.status = "retired"  # scratch copy only: compare every candidate on an equal footing
            mv = registry.train_candidate(db, actor, alg, now=now)
            db.commit()
            m, g = mv.metrics, mv.gates
            cal = m["calibration"]
            fair = {k.split(":", 1)[1]: {} for k in g if k.startswith("fairness_")}
            for k, v in g.items():
                if k.startswith("fairness_"):
                    kind, attr = k[len("fairness_"):].split(":", 1)
                    fair[attr][kind] = {"passed": v["passed"], "flagged": v["value"], "gap": v.get("gap")}
            results.append({"recalibration": method, "algorithm": alg, "chosen": cal["method"],
                            "n_train": mv.trained_on_n, "n_holdout": mv.validated_on_n, "auc": m["auc"],
                            "raw": {k: cal["raw"][k] for k in ("ece", "brier", "citl", "slope", "bins_within_ci", "bins")},
                            "final": {k: cal["calibrated"][k] for k in ("ece", "brier", "citl", "slope", "bins_within_ci", "bins")},
                            "reliability": cal["calibrated"]["reliability"], "tuning": cal.get("tuning"),
                            "gates_failed": [k for k, v in g.items() if k != "all_passed" and not v["passed"]],
                            "all_gates_passed": g["all_passed"], "fairness": fair})
    out = Path(a.out)
    jpath = out.with_suffix(".json")
    data = json.loads(jpath.read_text()) if jpath.exists() else {}
    data[a.name] = {"db": a.db, "as_of": str(now), "results": results}
    jpath.write_text(json.dumps(data, indent=1, default=str))
    out.with_suffix(".md").write_text(render(data))
    for r in results:
        print(f"[{a.name}] {r['algorithm']:6s} recal={r['recalibration']:4s}->{r['chosen']:5s} n={r['n_train']}/{r['n_holdout']} "
              f"AUC={r['auc']} ECE {r['raw']['ece']}->{r['final']['ece']} slope {r['raw']['slope']}->{r['final']['slope']} "
              f"CITL {r['final']['citl']} Brier {r['final']['brier']} bins {r['final']['bins_within_ci']}/{r['final']['bins']} "
              f"failed={r['gates_failed']}")
    shutil.rmtree(tmp, ignore_errors=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
