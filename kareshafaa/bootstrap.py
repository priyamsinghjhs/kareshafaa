"""Start-up data preparation for a working installation:  python -m kareshafaa.bootstrap

* Creates missing tables/columns (never drops anything).
* If the database already holds data, it is kept as it is - nothing is reset or overwritten on restart.
* If the database is EMPTY (first start, e.g. a new PostgreSQL database from DATABASE_URL), it is filled once with the
  reference data (organisations, programmes, sites, staff directory and accounts) and the sample patient records:
  copied row-for-row from the database prepared when the container image was built (so the tamper-evident audit
  chain and model registry stay intact), or generated by the seeder if no such copy exists.
* Keeps a database copy of every model file (kareshafaa.ml.registry.store_artifact), so a new container can restore
  the exact, integrity-checked model files after a redeploy.
Staff passwords are NOT set here: the app sets first passwords at start-up from the environment (accounts.py)."""
from __future__ import annotations

import fcntl
import logging
import os
import sys
import time
from contextlib import contextmanager
from pathlib import Path

from sqlalchemy import bindparam, create_engine, func, inspect, select, text
from sqlalchemy.engine import make_url

from .config import get_settings, storage_is_persistent
from .db import Base, get_engine, init_db, session_scope

log = logging.getLogger("kareshafaa.bootstrap")

# How long a starting instance waits for ANOTHER bootstrap (overlapping deploys) before giving up. Long enough for a
# first-start copy, short enough that a stuck holder cannot hang the deploy forever.
BOOTSTRAP_LOCK_WAIT_MS = 120_000


class BootstrapLockTimeout(RuntimeError):
    pass


def _bootstrap_lock_engine(url: str):
    """Dedicated engine for the bootstrap lock session: no pool, autocommit, and NOT the request pool's short
    lock_timeout (db.py), so this session can wait for another bootstrap."""
    from sqlalchemy.pool import NullPool

    return create_engine(url, poolclass=NullPool, isolation_level="AUTOCOMMIT",
                         connect_args={"application_name": "kareshafaa-bootstrap", "keepalives": 1,
                                       "keepalives_idle": 30, "keepalives_interval": 10, "keepalives_count": 3,
                                       "connect_timeout": 10})


def _is_lock_timeout(exc: BaseException) -> bool:
    orig = getattr(exc, "orig", exc)
    return getattr(orig, "sqlstate", None) == "55P03" or type(orig).__name__ == "LockNotAvailable"


@contextmanager
def postgres_bootstrap_lock(url: str, engine_factory=None, wait_ms: int = BOOTSTRAP_LOCK_WAIT_MS):
    """One bootstrap at a time across instances: session advisory lock BOOTSTRAP_LOCK_KEY (never the timed-jobs key,
    which the running instance holds for its whole life). Taken on the database's direct (unpooled) connection."""
    from .worker_lock import BOOTSTRAP_LOCK_KEY, direct_url

    eng = (engine_factory or _bootstrap_lock_engine)(direct_url(url))
    conn = None
    locked = False
    try:
        conn = eng.connect()
        conn.execute(text("SELECT set_config('lock_timeout', :v, false)"), {"v": str(int(wait_ms))})
        try:
            conn.execute(text("SELECT pg_advisory_lock(:k)"), {"k": BOOTSTRAP_LOCK_KEY})
        except Exception as e:  # noqa: BLE001
            if _is_lock_timeout(e):
                raise BootstrapLockTimeout(
                    f"another bootstrap still holds the start-up lock (key {BOOTSTRAP_LOCK_KEY}) after "
                    f"{wait_ms // 1000}s; not starting on a half-prepared database") from None
            raise
        locked = True
        yield
    finally:
        if conn is not None:
            if locked:
                try:
                    conn.execute(text("SELECT pg_advisory_unlock(:k)"), {"k": BOOTSTRAP_LOCK_KEY})
                except Exception:  # noqa: BLE001 - session gone: the database already released it
                    pass
            try:
                conn.close()
            except Exception:  # noqa: BLE001
                pass
        eng.dispose()


def _is_empty(eng) -> bool:
    from .models import Organization, Patient, User

    with eng.connect() as c:
        return all((c.execute(select(func.count()).select_from(t.__table__)).scalar() or 0) == 0
                   for t in (Organization, User, Patient))


def _source_path(target_url: str) -> Path | None:
    s = get_settings()
    cands = [os.environ.get("KARESHAFAA_BOOTSTRAP_SOURCE"), s.data_dir / "kareshafaa.db",
             s.data_dir / "kareshafaa_demo_seed.db"]
    for c in cands:
        if c and Path(c).is_file() and Path(c).stat().st_size > 0 and f"sqlite:///{Path(c)}" != target_url:
            return Path(c)
    return None


def copy_database(src_path: Path, target_eng, batch: int = 2000) -> dict:
    """Copy every table row-for-row from a SQLite file into the (empty) target database."""
    from . import models  # noqa: F401  (register tables)

    src = create_engine(f"sqlite:///{src_path}")
    src_cols = {t: {c["name"] for c in inspect(src).get_columns(t)} for t in inspect(src).get_table_names()}
    counts: dict[str, int] = {}
    done: set[str] = set()
    deferred: list[tuple] = []  # (table, fk column names): foreign keys into tables not copied yet (reference cycles)
    with src.connect() as sc, target_eng.begin() as tc:
        for table in Base.metadata.sorted_tables:
            if table.name not in src_cols:
                continue
            cols = [c for c in table.columns if c.name in src_cols[table.name]]
            later = [c.name for c in cols if c.nullable and any(fk.column.table.name not in done or
                                                                 fk.column.table.name == table.name
                                                                 for fk in c.foreign_keys)]
            if later:
                deferred.append((table, later))
            res = sc.execute(select(*cols))
            n = 0
            while True:
                rows = res.fetchmany(batch)
                if not rows:
                    break
                recs = [dict(r._mapping) for r in rows]
                for r in recs:
                    for k in later:
                        r[k] = None
                tc.execute(table.insert(), recs)
                n += len(rows)
            counts[table.name] = n
            done.add(table.name)
        for table, later in deferred:  # second pass: fill in the cyclic references
            pk = list(table.primary_key.columns)[0]
            res = sc.execute(select(pk, *[table.c[k] for k in later]))
            stmt = table.update().where(pk == bindparam("_pk")).values({k: bindparam("_" + k) for k in later})
            while True:
                rows = res.fetchmany(batch)
                if not rows:
                    break
                params = [{"_pk": r[0], **{"_" + k: r[i + 1] for i, k in enumerate(later)}} for r in rows
                          if any(r[i + 1] is not None for i in range(len(later)))]
                if params:
                    tc.execute(stmt, params)
        if target_eng.dialect.name == "postgresql":  # move id sequences past the copied ids
            for table in Base.metadata.sorted_tables:
                pk = list(table.primary_key.columns)
                if len(pk) == 1 and pk[0].name == "id" and pk[0].autoincrement in (True, "auto"):
                    # table names come from our own SQLAlchemy metadata (never user input); quoted anyway
                    q = tc.dialect.identifier_preparer.quote(table.name)
                    tc.execute(text("SELECT setval(pg_get_serial_sequence(:t, 'id'), "  # nosec B608
                                    f"COALESCE((SELECT MAX(id) FROM {q}), 1), "
                                    f"(SELECT MAX(id) FROM {q}) IS NOT NULL)"), {"t": q})
    src.dispose()
    return counts


def backfill_model_artifacts() -> int:
    from .ml.registry import store_artifact
    from .models import ModelVersion

    n = 0
    with session_scope() as db:
        for mv in db.scalars(select(ModelVersion)):
            n += bool(store_artifact(db, mv))
    return n


def backfill_booked_appointment_due() -> dict:
    """Waiting booked appointments get the current deadline rule (services/workflow.py); idempotent, every start."""
    from .services.workflow import backfill_booked_appointment_due as fix

    try:
        with session_scope() as db:
            return fix(db)
    except Exception as e:  # noqa: BLE001 - a derived-deadline fix must never stop the service from starting
        log.warning("booked-appointment deadline fix skipped: %s", type(e).__name__)
        return {"error": type(e).__name__}


def _prepare(s) -> dict:
    init_db()
    eng = get_engine()
    out: dict = {"database": eng.dialect.name, "persistent_storage": storage_is_persistent(s)}
    if not _is_empty(eng):
        out["action"] = "existing data kept"
    else:
        src = _source_path(s.database_url)
        t0 = time.time()
        if src is not None:
            out["action"] = f"first start: copied initial records from {src.name}"
            out["rows"] = sum(copy_database(src, eng).values())
        else:
            from .seed import seed

            out["action"] = "first start: generated initial records"
            seed(verbose=False)
        out["seconds"] = round(time.time() - t0, 1)
        init_db()  # indexes/triggers after a bulk copy (idempotent)
    out["model_files_saved_to_database"] = backfill_model_artifacts()
    out["booked_appointment_due"] = backfill_booked_appointment_due()
    # one-time data steps for SYN- sample patients only (guarded by data_migrations; never real records)
    if s.data_steps == "startup":
        from .db import session_factory
        from .services.sample_data import run_pending
        out["data_steps"] = run_pending(session_factory())
    else:
        out["data_steps"] = "after start-up (background)" if s.data_steps == "background" else "off"
    return out


def run() -> dict:
    s = get_settings()
    s.data_dir.mkdir(parents=True, exist_ok=True)
    fd = os.open(str(s.data_dir / ".bootstrap.lock"), os.O_CREAT | os.O_RDWR, 0o600)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX)
        backend = make_url(s.database_url).get_backend_name()
        if backend == "postgresql":  # one bootstrap (schema changes included) at a time across instances
            with postgres_bootstrap_lock(s.worker_lock_database_url or s.database_url):
                out = _prepare(s)
        else:
            out = _prepare(s)
        if backend == "sqlite" and s.mode == "production":
            log.warning("DATABASE_URL is not set: data is kept in SQLite on this server's disk%s.",
                        "" if storage_is_persistent(s) else " - a TEMPORARY disk: everything is lost on restart/redeploy;"
                        " set DATABASE_URL to a PostgreSQL database to keep it")
        return out
    finally:
        os.close(fd)


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s:     %(name)s %(message)s")
    try:
        print(f"kareshafaa.bootstrap: {run()}", file=sys.stderr, flush=True)
        if get_settings().public_demo:  # internal showcase mode only: restore its bundled copy (was a separate step)
            from .public_demo import reset_from_seed

            print(f"kareshafaa.bootstrap: showcase copy restored: {reset_from_seed(get_settings())}", file=sys.stderr, flush=True)
    except Exception:  # noqa: BLE001 - report clearly; the container must not start on a half-prepared database
        log.exception("bootstrap failed")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
