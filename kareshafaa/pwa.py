"""Installable PWA: web app manifest, root-scope service worker and an offline page.

Clinical safety / privacy rule (enforced here and tested in tests/test_pwa.py): the service worker caches ONLY the
static app shell (CSS, JS, icons) and the offline page. HTML pages and every /api/ or /fhir response are fetched
from the network and are NEVER written to the SW cache, so no patient data and no authenticated page survives on
a shared device. Offline, a page navigation shows /offline and an API call gets a JSON 503 ("nothing was saved").
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from fastapi import APIRouter
from fastapi.responses import HTMLResponse, JSONResponse, Response

from . import __version__

HERE = Path(__file__).resolve().parent
STATIC = HERE / "static"
BRAND = "KareShafaa"
THEME_COLOR = "#0a2b5e"  # logo navy (static/brand/, docs/BRAND.md)
BACKGROUND_COLOR = "#ffffff"
# URL paths that are never cacheable by the service worker (patient data / authenticated responses)
NEVER_CACHE_PREFIXES = ("/api/", "/fhir")
PUBLIC_PATHS = ("/manifest.webmanifest", "/sw.js", "/offline", "/starting")  # no data; not audited, never load-shed

router = APIRouter(include_in_schema=False)


def shell_assets() -> list[str]:
    """Static app-shell files to precache: CSS, JS, favicon and icons only (no samples, no data)."""
    files = [p for p in STATIC.rglob("*") if p.is_file() and p.suffix in (".css", ".js", ".svg", ".png")
             and "samples" not in p.parts]
    return ["/static/" + p.relative_to(STATIC).as_posix() for p in sorted(files)]


WAKE_AFTER_MS = 4000  # CONFIRM: show the "starting" page when a page takes longer than 4 s (cold start)
SHELL_REV = "brand-2"  # bump to force every installed app to re-fetch the shell (2: new logo, Oct 2026)


def _cache_version() -> str:
    h = hashlib.sha256((__version__ + SHELL_REV).encode())
    for url in shell_assets():
        h.update(url.encode())
        h.update((STATIC / url[len("/static/"):]).read_bytes())
    h.update((HERE / "templates" / "offline.html").read_bytes())
    h.update((HERE / "templates" / "starting.html").read_bytes())
    return h.hexdigest()[:12]


def manifest() -> dict:
    icons = [
        {"src": "/static/icons/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
        {"src": "/static/icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
        {"src": "/static/icons/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
    ]
    return {"id": "/", "name": BRAND, "short_name": BRAND, "lang": "en", "dir": "ltr",
            "description": f"{BRAND} - closing the screening-to-care loop",
            "start_url": "/", "scope": "/", "display": "standalone", "orientation": "any",
            "theme_color": THEME_COLOR, "background_color": BACKGROUND_COLOR, "categories": ["medical", "health"],
            "icons": icons}


SW_TEMPLATE = r"""// KareShafaa service worker (generated by kareshafaa/pwa.py). Version: __VERSION__
// SAFETY: caches ONLY the static app shell + the offline page. HTML pages and /api/ or /fhir responses are never
// cached (patient data / authenticated content must not persist on the device).
const CACHE = "kareshafaa-shell-__VERSION__";
const OFFLINE_URL = "/offline";
// Free hosting sleeps when idle; a cold start can take tens of seconds. If a page has not answered within
// WAKE_AFTER_MS, show the static "starting" page (no data), which waits for /healthz and then opens the page again.
const STARTING_URL = "/starting";
const WAKE_AFTER_MS = __WAKE_MS__;
const SHELL = __SHELL__;
const NEVER_CACHE = __NEVER__;

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL.concat([OFFLINE_URL, STARTING_URL]))).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(
    keys.filter((k) => k.startsWith("kareshafaa-") && k !== CACHE).map((k) => caches.delete(k))
  )).then(() => self.clients.claim()));
});

function offlineJson() {
  return new Response(JSON.stringify({ detail: "you are offline - nothing was read or saved; please retry when online" }),
    { status: 503, headers: { "Content-Type": "application/json", "Cache-Control": "no-store" } });
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;                      // writes always go straight to the network
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (NEVER_CACHE.some((p) => url.pathname.startsWith(p))) {
    event.respondWith(fetch(req).catch(offlineJson));    // network only, never cached
    return;
  }
  if (req.mode === "navigate") {                          // network-first; the page itself is never cached
    const net = fetch(req).catch(() => caches.match(OFFLINE_URL));
    if (url.searchParams.has("ks_wait")) { event.respondWith(net); return; }   // already waited once: just wait
    const slow = new Promise((r) => setTimeout(r, WAKE_AFTER_MS)).then(() => caches.match(STARTING_URL)).then((hit) => hit || net);
    event.respondWith(Promise.race([net, slow]));
    return;
  }
  if (SHELL.includes(url.pathname)) {                     // static shell: cache-first, refreshed in the background
    event.respondWith(caches.open(CACHE).then((c) => c.match(url.pathname).then((hit) => {
      const net = fetch(req).then((res) => { if (res.ok && res.type === "basic") c.put(url.pathname, res.clone()); return res; });
      return hit || net;
    })));
  }
  // anything else: browser default (network, HTTP cache rules), nothing stored by the SW
});
"""


def service_worker_js() -> str:
    return (SW_TEMPLATE.replace("__VERSION__", _cache_version()).replace("__WAKE_MS__", str(WAKE_AFTER_MS))
            .replace("__SHELL__", json.dumps(shell_assets()))
            .replace("__NEVER__", json.dumps(list(NEVER_CACHE_PREFIXES))))


@router.get("/manifest.webmanifest")
def manifest_route() -> JSONResponse:
    return JSONResponse(manifest(), media_type="application/manifest+json", headers={"Cache-Control": "no-cache"})


@router.get("/sw.js")
def sw_route() -> Response:
    return Response(service_worker_js(), media_type="application/javascript",
                    headers={"Cache-Control": "no-cache", "Service-Worker-Allowed": "/"})


@router.get("/starting", response_class=HTMLResponse)
def starting_route() -> HTMLResponse:
    html = (HERE / "templates" / "starting.html").read_text(encoding="utf-8")
    return HTMLResponse(html, headers={"Cache-Control": "no-cache"})


@router.get("/offline", response_class=HTMLResponse)
def offline_route() -> HTMLResponse:
    html = (HERE / "templates" / "offline.html").read_text(encoding="utf-8")
    return HTMLResponse(html, headers={"Cache-Control": "no-cache"})
